// pixels reverse-engineered into the geometry that would have produced them.
//
// HOW (see scratchpad extract5.py / finalize.py for the throwaway scripts):
//   1. Threshold the frame for the BRIGHT WHITE figure only: brightness > 80
//      AND chroma (max-min channel) < 48 — this rejects the RED circumscribing
//      circle and the BLUE square (both chromatic) and the dim grey epicycle
