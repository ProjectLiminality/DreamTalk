//   2. The pen is FINISHING at the head in this frame, so the head sits under a
//      tangle of epicycle rings and arrows; that tangle was blanked and a clean
//      head+neck bump synthesised on the axis (a DELIBERATE reconstruction).
//   3. The right-hand limbs are drawn thin/broken by frame 51, so rather than
//      trust them, the crisp LEFT half was closed into a silhouette and MIRRORED
//      about the figure's vertical axis (Da Vinci's figure is bilaterally
//      symmetric). The OUTER contour of that silhouette is this path — one clean
//      simple closed loop, which is exactly what a Fourier tracer wants (the
//      original's self-crossing single stroke is not recoverable unambiguously
//      from pixels, and its outer envelope reads identically as the figure).
//   4. Smoothed, resampled to a fixed count, normalised: ~520 scene units tall,
